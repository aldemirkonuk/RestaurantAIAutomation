def cn(name):
    """canonical_name: lowercase, underscores, ltree-safe."""
    nfd = unicodedata.normalize('NFD', name)
    s = ''.join(c for c in nfd if unicodedata.category(c) != 'Mn')
    out = ''
    for c in s.lower():
        if c.isalnum(): out += c
        elif c in ' -/\'.,&()': out += '_'
    while '__' in out: out = out.replace('__', '_')
    return out.strip('_') or 'unknown'

def row(name, level, cc, system, aliases='{}'):
    c = cn(name)
    n = name.replace("'", "''")
    a = aliases if aliases else '{}'
    return (f"INSERT INTO wine_regions (name, level, country_code, classification_system, "
            f"canonical_name, aliases, source_ref) VALUES "
            f"('{n}', '{level}', '{cc}', '{system}', '{c}', '{a}', 'hardcoded-seed-v1');")

