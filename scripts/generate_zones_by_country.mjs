#!/usr/bin/env node
// Writes apps/web/src/lib/zonesByCountry.ts from a tzdb `zone.tab` (OB-7).
// Usage: node scripts/generate_zones_by_country.mjs [path/to/zone.tab] > apps/web/src/lib/zonesByCountry.ts
// Default source: the system tzdb (/usr/share/zoneinfo), whose version is
// read from +VERSION when it is there.
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const source = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab'
const versionFile = join(dirname(source), '+VERSION')
const version = existsSync(versionFile) ? readFileSync(versionFile, 'utf8').trim() : 'unknown'

const byCountry = {}
for (const line of readFileSync(source, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [code, , zone] = line.split('\t')
  ;(byCountry[code] ??= []).push(zone)
}

const quote = (zone) => `'${zone}'`
let out = `/**
 * Every IANA zone each country uses, from tzdb \`zone.tab\` (tzdata ${version}).
 * GENERATED by scripts/generate_zones_by_country.mjs: do not edit by hand.
 *
 * \`zone.tab\` (not \`zone1970.tab\`) is the source because it lists each
 * country under its own zone names (Europe/Zagreb for HR, not the merged
 * Europe/Belgrade), which is what a person expects to see for their house.
 * Read by \`zoneForPlace\` (OB-7): the house's clock is never a zone from
 * outside the place's country.
 */
export const ZONES_BY_COUNTRY: Readonly<Record<string, readonly string[]>> = {
`
for (const code of Object.keys(byCountry).sort()) {
  out += `  ${code}: [${byCountry[code].map(quote).join(', ')}],\n`
}
out += '}\n'
process.stdout.write(out)
